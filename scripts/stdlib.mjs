import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const root = 'lib';
const out = {};
async function walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) await walk(p);
    else if (e.name.endsWith('.kerf'))
      out[relative(root, p).split(sep).join('/').slice(0, -'.kerf'.length)] = (
        await readFile(p, 'utf8')
      ).replace(/\r\n/g, '\n');
  }
}
await walk(root);
await writeFile(
  'src/stdlib.ts',
  `// Generated by scripts/stdlib.mjs from lib/. Do not edit.\n\nexport const LIBRARIES: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
